#!/usr/bin/env python3
"""Create small WebP copies of site photos for phones and cards.

For every JPG/PNG/WebP under jbresidence-site/ that is wider than 760px, writes
  img-r/<same path without extension>-720.webp   (cards, thumbnails)
  img-r/<same path without extension>-1200.webp  (phone heroes; only if wider than 1200px)
and regenerates the variant list inside js/main.js and js/main-v3.98.js
(between the IMG_VARIANTS markers) so cards use the small copies automatically.

Safe to run again any time (skips copies that are already up to date).
Run after adding new photos:   python3 tools/make-responsive-images.py
"""
import os, re, json, sys
from PIL import Image, ImageOps
SITE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'jbresidence-site')
os.chdir(SITE)
SIZES = (720, 1200)
SKIP_DIRS = {'img-r', 'fonts', 'node_modules', '.git'}
variants = {}
made = 0
for root, dirs, files in os.walk('.'):
    dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
    for fn in files:
        if not fn.lower().endswith(('.jpg', '.jpeg', '.png', '.webp')): continue
        src = os.path.normpath(os.path.join(root, fn))
        if 'floor-plan' in src.lower(): continue
        try:
            im = Image.open(src); w, h = im.size
        except Exception:
            continue
        if w <= 760: continue
        have = []
        for s in SIZES:
            if s == 1200 and w <= 1200: continue
            out = os.path.join('img-r', os.path.splitext(src)[0] + f'-{s}.webp')
            if not os.path.exists(out) or os.path.getmtime(out) < os.path.getmtime(src):
                os.makedirs(os.path.dirname(out), exist_ok=True)
                x = ImageOps.exif_transpose(Image.open(src))
                x = x.convert('RGBA' if x.mode in ('RGBA', 'LA', 'P') else 'RGB')
                x.thumbnail((s, s * 4), Image.LANCZOS)
                x.save(out, 'WEBP', quality=78, method=6)
                made += 1
            have.append(s)
        variants[src.replace(os.sep, '/')] = [have, w, h]
manifest = json.dumps(variants, separators=(',', ':'), sort_keys=True)
block = ("/* IMG_VARIANTS:START (generated by tools/make-responsive-images.py — do not edit by hand) */\n"
         f"const IMG_VARIANTS = {manifest};\n"
         "function imgVariant(url, size) {\n"
         "  if (!url || /^https?:\\/\\//.test(url)) return url;\n"
         "  const key = decodeURI(url).replace(/^\\.?\\.?\\//, '').replace(/^\\//, '');\n"
         "  const v = IMG_VARIANTS[key];\n"
         "  if (!v) return url;\n"
         "  const pick = v[0].find(s => s >= size) || v[0][v[0].length - 1];\n"
         "  return '/img-r/' + key.replace(/\\.[^.]+$/, '') + '-' + pick + '.webp';\n"
         "}\n"
         "/* IMG_VARIANTS:END */")
for js in ('js/main.js', 'js/main-v3.98.js'):
    s = open(js, encoding='utf-8').read()
    if 'IMG_VARIANTS:START' in s:
        s = re.sub(r'/\* IMG_VARIANTS:START.*?IMG_VARIANTS:END \*/', lambda m: block, s, flags=re.S)
    else:
        s = block + '\n\n' + s
    open(js, 'w', encoding='utf-8').write(s)
json.dump(variants, open('img-r/variants.json', 'w'), indent=0, sort_keys=True)
print(f'{len(variants)} photos have small copies; {made} new files written')
